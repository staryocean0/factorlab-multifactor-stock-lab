def builtin_factor_registry() -> dict[str, FactorSpec]:
    return {spec.factor_id: spec for spec in BUILTIN_FACTOR_SPECS}


def factor_specs_as_records() -> list[dict[str, object]]:
    return [spec.__dict__.copy() for spec in BUILTIN_FACTOR_SPECS]


def factor_specs_from_records(records: list[dict[str, object]]) -> tuple[FactorSpec, ...]:
    specs: list[FactorSpec] = []
    required = set(FactorSpec.__dataclass_fields__)
    for index, record in enumerate(records):
        missing = required - set(record)
        if missing:
            raise ValueError(f"factor spec record {index} missing fields: {sorted(missing)}")
        required_columns = record["required_columns"]
        if not isinstance(required_columns, (list, tuple)):
            raise ValueError(f"factor spec record {index} required_columns must be a list")
        spec = FactorSpec(
            factor_id=str(record["factor_id"]),
            version=str(record["version"]),
            source_class=str(record["source_class"]),
            source_family=str(record["source_family"]),
            direction=str(record["direction"]),
            lookback=int(record["lookback"]),
            required_columns=tuple(str(column) for column in required_columns),
            availability_group=str(record["availability_group"]),
            activation_state=str(record["activation_state"]),
            default_enabled=bool(record["default_enabled"]),
            pit_policy=str(record["pit_policy"]),
            description=str(record["description"]),
            notes=str(record.get("notes", "")),
        )
        if spec.default_enabled and spec.activation_state != "active":
            raise ValueError(f"factor spec {spec.factor_id} cannot be default_enabled unless active")
        specs.append(spec)
    factor_ids = [spec.factor_id for spec in specs]
    duplicates = sorted({factor_id for factor_id in factor_ids if factor_ids.count(factor_id) > 1})
    if duplicates:
        raise ValueError(f"duplicate factor specs: {duplicates}")
    return tuple(specs)


def enabled_factor_specs(
    specs: tuple[FactorSpec, ...] | None = None,
) -> tuple[FactorSpec, ...]:
    source = specs or BUILTIN_FACTOR_SPECS
    return tuple(spec for spec in source if spec.default_enabled and spec.activation_state == "active")
